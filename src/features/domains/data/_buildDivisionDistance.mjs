// Regenerates ./divisionDistance.js
// Run from anywhere:  node src/features/domains/data/_buildDivisionDistance.mjs
// (must be inside the `front` package so @turf resolves)
//
// Polygon centroid [lon, lat] for every division, from the same Domains.json
// the Hunting Difficulty builder uses. The Feeding domain picker measures
// distance from these at runtime — from division 39 (Athina, the historic
// city centre) when the player has no domain of their own, or from their own
// domain when they do, so "closer" always means something useful to them.
// Re-run after changing Domains.json.
import centroid from '@turf/centroid';
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const HERE = dirname(fileURLToPath(import.meta.url));
const domains = JSON.parse(readFileSync(join(HERE, '../../../data/Domains.json'), 'utf8'));

const CENTRE_DIVISION = 39; // Athina

const out = {};
for (const f of domains.features) {
  const div = f.properties?.division;
  if (div == null) continue;
  const [lon, lat] = centroid(f).geometry.coordinates;
  out[div] = [+lon.toFixed(5), +lat.toFixed(5)];
}

const body = `// AUTO-GENERATED by ./_buildDivisionDistance.mjs — do not hand-edit.
// Polygon centroid [lon, lat] per division, from Domains.json. Re-run the
// builder after changing Domains.json.

export const CENTRE_DIVISION = ${CENTRE_DIVISION};

export const DIVISION_CENTROIDS = ${JSON.stringify(out, null, 2)};

function haversineKm([lon1, lat1], [lon2, lat2]) {
  const R = 6371;
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a = Math.sin(dLat / 2) ** 2
    + Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

// Straight-line distance (km) between any two divisions' centroids, rounded
// to 2 decimals. Returns null if either division is unknown.
export function distanceKm(divA, divB) {
  const a = DIVISION_CENTROIDS[divA];
  const b = DIVISION_CENTROIDS[divB];
  if (!a || !b) return null;
  return Math.round(haversineKm(a, b) * 100) / 100;
}

export function distanceFromCentre(division) {
  return distanceKm(division, CENTRE_DIVISION);
}
`;
writeFileSync(join(HERE, 'divisionDistance.js'), body);
console.log('wrote', join(HERE, 'divisionDistance.js'), '—', Object.keys(out).length, 'divisions');
