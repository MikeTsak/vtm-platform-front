// Regenerates ./huntingDifficulty.js
// Run from anywhere:  node src/features/domains/data/_buildHuntingDifficulty.mjs
// (must be inside the `front` package so @turf resolves)
//
// Hunting Difficulty per map division, from effective population + polygon area.
// Both density extremes are hard; a mid band (≈ D_IDEAL) is easy; the historic
// centre is 7. See ../../../../../HUNTING_DIFFICULTY_PLAN.md.
import area from '@turf/area';
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const HERE = dirname(fileURLToPath(import.meta.url));
const domains = JSON.parse(readFileSync(join(HERE, '../../../data/Domains.json'), 'utf8'));
const popSrc = readFileSync(join(HERE, 'divisionPopulations.js'), 'utf8');

// DIVISION_POPULATIONS -> { div: {population, group} }
const POP = {};
for (const m of popSrc.matchAll(/^\s*(\d+):\s*\{\s*population:\s*(\d+)[^}]*?group:\s*'([^']+)'/gm)) {
  POP[+m[1]] = { population: +m[2], group: m[3] };
}
const GROUP_MEMBERS = {};
for (const [d, info] of Object.entries(POP)) (GROUP_MEMBERS[info.group] ??= []).push(+d);

// Outer-Attica divisions (50–82) have no census row here — best-effort estimates.
const EXTRA_POP = {
  50: 5000, 51: 11000, 52: 3000, 53: 3000, 54: 1000, 55: 7000,
  56: 33000, 57: 10000, 58: 3500, 59: 4500, 60: 4000, 61: 10000,
  62: 7000, 63: 5500, 64: 6500, 65: 30000, 66: 35000, 67: 5500,
  68: 1200, 69: 13000, 70: 1500, 71: 3500, 72: 16000, 73: 3000,
  74: 3500, 75: 2500, 76: 10000, 77: 3000, 78: 2500, 79: 3500,
  80: 2000, 81: 2500, 82: 2300,
};

function effectivePopulation(div) {
  if (POP[div]) {
    const { population, group } = POP[div];
    const n = (GROUP_MEMBERS[group] || [div]).length;
    return { pop: Math.round(population / n), estimated: false };
  }
  return { pop: EXTRA_POP[div] ?? 4000, estimated: true };
}

const D_IDEAL = 6000;                       // people/km² — the easy sweet spot
// Always Lethal (7) regardless of the density math: the historic dead centre
// plus Piraeus — the port, wall-to-wall watchers, organised eyes everywhere.
const ALWAYS_LETHAL = new Set([8, 39, 40, 43]); // Plaka, Athina, Psyrri, Piraeus
const CENTRE_DENSITY = 42000;

function difficultyFor(density, pop, div) {
  const l = Math.log10(density / D_IDEAL);
  let raw = l >= 0 ? 2 + l * 5.5 : 2 + (-l) * 3.1;  // crowded side steeper
  if (pop < 9000) raw += 0.6;
  let d = Math.max(2, Math.min(6, Math.round(raw)));
  if (ALWAYS_LETHAL.has(div) || density >= CENTRE_DENSITY) d = 7;
  return d;
}

const out = {};
const rows = [];
for (const f of domains.features) {
  const div = f.properties?.division;
  if (div == null) continue;
  const areaKm2 = area(f) / 1e6;
  const ep = effectivePopulation(div);
  const density = ep.pop / areaKm2;
  const difficulty = difficultyFor(density, ep.pop, div);
  out[div] = {
    difficulty,
    density: Math.round(density),
    areaKm2: +areaKm2.toFixed(3),
    effectivePopulation: ep.pop,
    estimated: ep.estimated,
  };
  rows.push({ div, name: f.properties.name, ...out[div] });
}

rows.sort((a, b) => a.difficulty - b.difficulty || b.density - a.density);
for (const r of rows) console.log(String(r.div).padStart(3), r.difficulty, String(r.density).padStart(7), String(r.areaKm2).padStart(8), String(r.effectivePopulation).padStart(7), r.name);
const dist = {};
for (const r of rows) dist[r.difficulty] = (dist[r.difficulty] || 0) + 1;
console.log('distribution', dist, 'total', rows.length);

const body = `// AUTO-GENERATED by ./_buildHuntingDifficulty.mjs — do not hand-edit.
// Hunting Difficulty per map division, from effective population + area: both
// density extremes (packed / empty) are hard, a mid band is easy; the historic
// centre is 7. Re-run the builder after changing Domains.json or population data.

export const HUNTING_DIFFICULTY_MAX = 7;

export const HUNTING_DIFFICULTY = ${JSON.stringify(out, null, 2)};

const LABELS = { 2: 'Easy', 3: 'Easy', 4: 'Moderate', 5: 'Hard', 6: 'Severe', 7: 'Lethal' };
export function huntingLabel(n) { return LABELS[n] || '—'; }

export function huntingDifficulty(division) {
  return HUNTING_DIFFICULTY[division]?.difficulty ?? null;
}
`;
writeFileSync(join(HERE, 'huntingDifficulty.js'), body);
console.log('wrote', join(HERE, 'huntingDifficulty.js'));
